// Принцип: арки — эмоции, а не источник дохода (награды умеренные); выбор всегда за игроком.
// Тексты поддерживают плейсхолдер {name} — UI подставляет имя участника (story.arcs[id].staffName).

export interface StoryOption {
  id: string;
  label: string;
  hint?: string;
  /** разовая цена в K (опция не показывается, если денег не хватает) */
  cost?: number;
  /** разовая выплата в K */
  money?: number;
  /** фанаты (обычно в эпилогах) */
  fans?: number;
}

export interface StoryStep {
  title: string;
  text: string;
  options: StoryOption[];
}

export interface StoryArc {
  id: string;
  /** через сколько недель после завязки приходит эпилог */
  epilogueAfterWeeks: number;
  /** [0] — завязка; [1] — эпилог «остался»; [2] — эпилог «ушёл» (выбор делает движок) */
  steps: StoryStep[];
}

